type BinaryState = {
  values: number[];
  left: number;
  right: number;
  mid: number;
  excluded: number[];
  answer: string;
  note: string;
  secondValues?: number[];
  columns?: number;
  i?: number;
  j?: number;
  partitionLines?: [number, number];
  al?: string;
  ar?: string;
  bl?: string;
  br?: string;
  phase?: string;
};

type StackState = {
  values: (number | string)[];
  stack: (number | string)[];
  index: number;
  answer: string;
  note: string;
  pairs?: [number, number][];
  minima?: number[];
  operation?: string;
  appendedSentinel?: boolean;
};

type HeapState = {
  values: number[];
  heap: number[];
  index: number;
  answer: string;
  note: string;
  stream?: number[];
  counts?: [number, number][];
  heapEntries?: [number, number][];
  leftHeap?: number[];
  rightHeap?: number[];
  phase?: string;
};

function binaryFrame(title: string, detail: string, state: BinaryState) {
  return { title, detail, state };
}

function stackFrame(title: string, detail: string, state: StackState) {
  return { title, detail, state };
}

function heapFrame(title: string, detail: string, state: HeapState) {
  return { title, detail, state };
}

